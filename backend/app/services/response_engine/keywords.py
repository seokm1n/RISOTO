def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").lower())


def hit_counts(texts: list[str]) -> dict[str, int]:
    """유형별 '히트한 문서 수'. 한 문서 안 중복 등장은 1로 센다(모듈 docstring 참고)."""
    counts = {code: 0 for code in TYPE_KEYWORDS}
    for text in texts:
        norm = _normalize(text)
        for code, words in TYPE_KEYWORDS.items():
            if any(w in norm for w in words):
                counts[code] += 1
    return counts


def looks_negative(text: str) -> bool:
    norm = _normalize(text)
    return any(w in norm for w in NEGATIVE_HINTS)
